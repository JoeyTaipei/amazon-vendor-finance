-- OPS: action items written only through procedures (governed write-back), search glossary, MCP.
CREATE TABLE IF NOT EXISTS AMAZON_FINANCE_APP.OPS.ACTION_ITEMS (
  ID NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
  TYPE VARCHAR NOT NULL, ENTITY_TYPE VARCHAR, ENTITY_ID VARCHAR, AMOUNT NUMBER(18,2),
  PRIORITY VARCHAR DEFAULT 'medium', OWNER VARCHAR, STATUS VARCHAR DEFAULT 'open', DUE_DATE DATE,
  CREATED_BY VARCHAR, CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_AT TIMESTAMP_LTZ,
  SOURCE VARCHAR DEFAULT 'user', NOTES VARCHAR, OUTCOME_AMOUNT NUMBER(18,2), RECOMMENDATION_ID NUMBER);

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.OPS.ACTION_ITEMS_V AS SELECT * FROM AMAZON_FINANCE_APP.OPS.ACTION_ITEMS;

CREATE OR REPLACE PROCEDURE AMAZON_FINANCE_APP.OPS.CREATE_ACTION_ITEM(
  P_TYPE VARCHAR, P_ENTITY_TYPE VARCHAR, P_ENTITY_ID VARCHAR, P_AMOUNT FLOAT, P_PRIORITY VARCHAR, P_NOTES VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER
AS
$$
DECLARE
  new_id NUMBER;
BEGIN
  IF (:P_TYPE NOT IN ('dispute_shortage','classify_deduction','chase_payment','coop_review','price_fix')) THEN
    RETURN 'ERROR: type must be one of dispute_shortage, classify_deduction, chase_payment, coop_review, price_fix';
  END IF;
  IF (COALESCE(:P_PRIORITY,'medium') NOT IN ('low','medium','high')) THEN
    RETURN 'ERROR: priority must be low, medium or high';
  END IF;
  INSERT INTO AMAZON_FINANCE_APP.OPS.ACTION_ITEMS (TYPE, ENTITY_TYPE, ENTITY_ID, AMOUNT, PRIORITY, STATUS, CREATED_BY, SOURCE, NOTES)
    VALUES (:P_TYPE, :P_ENTITY_TYPE, :P_ENTITY_ID, :P_AMOUNT, COALESCE(:P_PRIORITY,'medium'), 'open', CURRENT_USER(), 'agent', :P_NOTES);
  SELECT MAX(ID) INTO :new_id FROM AMAZON_FINANCE_APP.OPS.ACTION_ITEMS WHERE CREATED_BY = CURRENT_USER();
  RETURN 'Created action item ' || :new_id;
END;
$$;

CREATE OR REPLACE PROCEDURE AMAZON_FINANCE_APP.OPS.UPDATE_ACTION_ITEM(
  P_ID NUMBER, P_STATUS VARCHAR, P_OWNER VARCHAR, P_NOTES VARCHAR, P_OUTCOME_AMOUNT FLOAT)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER
AS
$$
DECLARE
  n NUMBER;
BEGIN
  IF (:P_STATUS IS NOT NULL AND :P_STATUS NOT IN ('open','in_progress','done','dismissed')) THEN
    RETURN 'ERROR: status must be open, in_progress, done or dismissed';
  END IF;
  SELECT COUNT(*) INTO :n FROM AMAZON_FINANCE_APP.OPS.ACTION_ITEMS WHERE ID = :P_ID;
  IF (:n = 0) THEN
    RETURN 'ERROR: action item ' || :P_ID || ' not found';
  END IF;
  UPDATE AMAZON_FINANCE_APP.OPS.ACTION_ITEMS
     SET STATUS = COALESCE(:P_STATUS, STATUS),
         OWNER = COALESCE(:P_OWNER, OWNER),
         NOTES = IFF(:P_NOTES IS NULL, NOTES, COALESCE(NOTES || ' | ', '') || :P_NOTES),
         OUTCOME_AMOUNT = COALESCE(:P_OUTCOME_AMOUNT, OUTCOME_AMOUNT),
         UPDATED_AT = CURRENT_TIMESTAMP()
   WHERE ID = :P_ID;
  RETURN 'Updated action item ' || :P_ID;
END;
$$;

CREATE OR REPLACE PROCEDURE AMAZON_FINANCE_APP.OPS.LIST_ACTION_ITEMS(P_STATUS VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER
AS
$$
DECLARE
  out VARCHAR;
BEGIN
  SELECT COALESCE(ARRAY_AGG(OBJECT_CONSTRUCT_KEEP_NULL('id',ID,'type',TYPE,'entity_type',ENTITY_TYPE,'entity_id',ENTITY_ID,'amount',AMOUNT,
           'priority',PRIORITY,'owner',OWNER,'status',STATUS,'created_by',CREATED_BY,'created_at',CREATED_AT,'notes',NOTES,'outcome_amount',OUTCOME_AMOUNT))
           WITHIN GROUP (ORDER BY ID DESC), ARRAY_CONSTRUCT())::VARCHAR
    INTO :out
    FROM (SELECT * FROM AMAZON_FINANCE_APP.OPS.ACTION_ITEMS WHERE :P_STATUS IS NULL OR :P_STATUS = '' OR STATUS = :P_STATUS ORDER BY ID DESC LIMIT 50);
  RETURN :out;
END;
$$;

-- Search glossary is copied locally: the shared database can't have change tracking enabled.
CREATE OR REPLACE TABLE AMAZON_FINANCE_APP.OPS.DEDUCTION_GLOSSARY AS
SELECT DESCRIPTION, DEDUCTION_CATEGORY, COUNT(*) AS LINES, ROUND(SUM(AMOUNT),2) AS TOTAL_AMOUNT,
  DESCRIPTION || ' (category: ' || DEDUCTION_CATEGORY || IFF(ANY_VALUE(IS_PROVISION), ', accounting provision - not a deduction', '') || ')' AS SEARCH_TEXT
FROM AMAZON_FINANCE_APP.STAGING.REMITTANCE_LINES WHERE DESCRIPTION IS NOT NULL GROUP BY 1, 2;

CREATE OR REPLACE CORTEX SEARCH SERVICE AMAZON_FINANCE_APP.OPS.AMZ_TEXT_SEARCH ON SEARCH_TEXT ATTRIBUTES DEDUCTION_CATEGORY
  WAREHOUSE = AMZ_FIN_WH TARGET_LAG = '1 day'
AS SELECT SEARCH_TEXT, DESCRIPTION, DEDUCTION_CATEGORY, LINES, TOTAL_AMOUNT FROM AMAZON_FINANCE_APP.OPS.DEDUCTION_GLOSSARY;

