-- MARTS: app-facing views (App interface). Source share is static and read-only, so views instead of dynamic tables.
CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.SHORTAGE_RECOVERY AS
WITH d AS (
  SELECT DATE_TRUNC('MONTH', INVOICE_DATE) AS MONTH, -SUM(AMOUNT) AS SHORTAGE_DEDUCTED, COUNT(*) AS SHORTAGE_LINES
  FROM AMAZON_FINANCE_APP.STAGING.REMITTANCE_LINES WHERE IS_SHORTAGE GROUP BY 1
), r AS (
  SELECT DATE_TRUNC('MONTH', DISPUTE_DATE) AS MONTH, SUM(DISPUTE_AMOUNT) AS DISPUTED, SUM(RESOLVED_AMOUNT) AS RECOVERED
  FROM AMAZON_FINANCE_APP.STAGING.DISPUTES GROUP BY 1
)
SELECT COALESCE(d.MONTH, r.MONTH) AS MONTH,
       COALESCE(d.SHORTAGE_DEDUCTED, 0) AS SHORTAGE_DEDUCTED,
       COALESCE(d.SHORTAGE_LINES, 0) AS SHORTAGE_LINES,
       COALESCE(r.DISPUTED, 0) AS DISPUTED,
       COALESCE(r.RECOVERED, 0) AS RECOVERED,
       COALESCE(r.RECOVERED, 0) / NULLIF(d.SHORTAGE_DEDUCTED, 0) AS RECOVERY_RATE
FROM d FULL OUTER JOIN r ON d.MONTH = r.MONTH;

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.DEDUCTIONS_BY_CATEGORY AS
SELECT DATE_TRUNC('MONTH', INVOICE_DATE) AS MONTH,
       DEDUCTION_CATEGORY,
       DEDUCTION_CATEGORY = 'UNCATEGORIZED' AS IS_UNEXPLAINED,
       COUNT(*) AS LINES,
       -SUM(AMOUNT) AS DEDUCTION_AMOUNT
FROM AMAZON_FINANCE_APP.STAGING.REMITTANCE_LINES
WHERE IS_DEDUCTION
GROUP BY 1, 2;

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.UNPAID_INVOICE_AGING AS
SELECT INVOICE_NUMBER, INVOICE_DATE, PAYMENT_DUE_DATE, INVOICE_STATUS, INVOICE_AMOUNT, PAID_AMOUNT, UNPAID_AMOUNT,
       DATEDIFF('day', PAYMENT_DUE_DATE, CURRENT_DATE) AS DAYS_PAST_DUE,
       CASE WHEN DATEDIFF('day', PAYMENT_DUE_DATE, CURRENT_DATE) <= 0 THEN 'Not due'
            WHEN DATEDIFF('day', PAYMENT_DUE_DATE, CURRENT_DATE) <= 30 THEN '1-30'
            WHEN DATEDIFF('day', PAYMENT_DUE_DATE, CURRENT_DATE) <= 60 THEN '31-60'
            ELSE '60+' END AS AGING_BUCKET
FROM AMAZON_FINANCE_APP.STAGING.INVOICES
WHERE UNPAID_AMOUNT > 0.01;

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.CASH_COLLECTION AS
SELECT DATE_TRUNC('MONTH', INVOICE_DATE) AS MONTH,
       COUNT(*) AS INVOICES,
       SUM(INVOICE_AMOUNT) AS INVOICED,
       SUM(PAID_AMOUNT) AS PAID,
       SUM(UNPAID_AMOUNT) AS UNPAID
FROM AMAZON_FINANCE_APP.STAGING.INVOICES
GROUP BY 1;

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.COOP_BY_AGREEMENT AS
SELECT AGREEMENT_ID, AGREEMENT_TITLE, FUNDING_TYPE,
       COUNT(*) AS CHARGES, SUM(COOP_AMOUNT) AS COOP_AMOUNT,
       MIN(INVOICE_DATE) AS FIRST_CHARGE, MAX(INVOICE_DATE) AS LAST_CHARGE
FROM AMAZON_FINANCE_APP.STAGING.COOP
GROUP BY 1, 2, 3;

CREATE OR REPLACE VIEW AMAZON_FINANCE_APP.MARTS.KPI_SUMMARY AS
WITH i AS (SELECT SUM(INVOICE_AMOUNT) AS INVOICED, SUM(PAID_AMOUNT) AS PAID, SUM(UNPAID_AMOUNT) AS UNPAID FROM AMAZON_FINANCE_APP.STAGING.INVOICES),
     d AS (SELECT -SUM(AMOUNT) AS TOTAL_DEDUCTIONS,
                  -SUM(IFF(IS_SHORTAGE, AMOUNT, 0)) AS SHORTAGE_DEDUCTED,
                  -SUM(IFF(DEDUCTION_CATEGORY = 'UNCATEGORIZED', AMOUNT, 0)) AS UNEXPLAINED_DEDUCTIONS
           FROM AMAZON_FINANCE_APP.STAGING.REMITTANCE_LINES WHERE IS_DEDUCTION),
     r AS (SELECT SUM(RESOLVED_AMOUNT) AS RECOVERED FROM AMAZON_FINANCE_APP.STAGING.DISPUTES)
SELECT i.INVOICED, i.PAID, i.UNPAID,
       d.TOTAL_DEDUCTIONS, d.SHORTAGE_DEDUCTED, r.RECOVERED,
       r.RECOVERED / NULLIF(d.SHORTAGE_DEDUCTED, 0) AS SHORTAGE_RECOVERY_RATE,
       d.UNEXPLAINED_DEDUCTIONS,
       1 - d.UNEXPLAINED_DEDUCTIONS / NULLIF(d.TOTAL_DEDUCTIONS, 0) AS CATEGORIZED_SHARE
FROM i, d, r;
